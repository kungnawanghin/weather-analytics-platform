-- PostgreSQL schema for a new Supabase project.
-- Run once in Supabase SQL Editor. Keep database/schema.sql for local SQLite.
begin;

create table public.areas (
  id text primary key,
  name text not null,
  province_name text not null,
  level text not null check (level in ('province', 'district')),
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180)
);

create table public.weather_records (
  id bigint generated by default as identity primary key,
  area_id text not null references public.areas(id),
  source text not null,
  model text not null,
  valid_at timestamptz not null,
  fetched_at timestamptz not null,
  temperature_c double precision not null,
  humidity_percent double precision not null check (humidity_percent between 0 and 100),
  wind_speed_kmh double precision not null check (wind_speed_kmh >= 0),
  unique (area_id, source, model, valid_at)
);

-- No public policies: access will use a server-only credential.
alter table public.areas enable row level security;
alter table public.weather_records enable row level security;

commit;

select c.relname as table_name, c.relrowsecurity as rls_enabled
from pg_class c join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and c.relname in ('areas', 'weather_records')
order by c.relname;
